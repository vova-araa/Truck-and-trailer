const KEY = "tt_lang";

export function getLang() {
  try {
    const l = localStorage.getItem(KEY);
    if (l && LANGS.some((x) => x.code === l)) return l;
  } catch { /* geen localStorage */ }
  return "nl";
}

export function setLang(code) {
  try { localStorage.setItem(KEY, code); } catch { /* noop */ }
  if (typeof window !== "undefined") window.dispatchEvent(new CustomEvent("tt-lang", { detail: code }));
}

// Vertaling ophalen. Valt terug op Nederlands, dan op de sleutel zelf.
export function t(key, lang = getLang()) {
  const d = DICT[lang] || DICT.nl;
  if (d && d[key] != null) return d[key];
  if (DICT.nl[key] != null) return DICT.nl[key];
  return key;
}

